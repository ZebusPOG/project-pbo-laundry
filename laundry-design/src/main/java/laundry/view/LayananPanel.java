    @Override
    protected void loadData() {
        DefaultTableModel model = (DefaultTableModel) tblLayanan.getModel();
        model.setRowCount(0);
        try {
            for (Layanan l : layananDAO.findAll()) {
                model.addRow(new Object[]{l.getIdLayanan(), l.getNamaLayanan(),
                    Format.rupiah(l.getHargaPerKg()), l.getEstimasiHari()});
            }
        } catch (SQLException ex) {
            showErrorDatabase("memuat data layanan", ex);
        }
    }

    @Override
    protected void resetForm() {
        txtNamaLayanan.setText("");
        txtHarga.setText("");
        txtEstimasi.setText("");
        hapusError(txtNamaLayanan, lblErrorNama);
        hapusError(txtHarga, lblErrorHarga);
        hapusError(txtEstimasi, lblErrorEstimasi);
        idTerpilih = -1;
        tblLayanan.clearSelection();
    }

    /**
     * Membaca dan memeriksa isi form.
     * Mengembalikan objek Layanan, atau null jika ada isian yang salah (diberi garis merah).
     */
    private Layanan bacaForm() {
        hapusError(txtNamaLayanan, lblErrorNama);
        hapusError(txtHarga, lblErrorHarga);
        hapusError(txtEstimasi, lblErrorEstimasi);
        boolean valid = true;

        String nama = txtNamaLayanan.getText().trim();
        if (nama.isEmpty()) {
            tandaiError(txtNamaLayanan, lblErrorNama, "Nama layanan wajib diisi");
            valid = false;
        }

        double harga = 0;
        try {
            harga = Format.bacaRupiah(txtHarga.getText());
        } catch (NumberFormatException ex) {
            harga = 0;
        }
        if (harga <= 0) {
            tandaiError(txtHarga, lblErrorHarga, "Harga harus angka, contoh: 8000");
            valid = false;
        }

        int estimasi = 2; // jika kosong, pakai 2 hari (sesuai rancangan database)
        if (!txtEstimasi.getText().trim().isEmpty()) {
            try {
                estimasi = Integer.parseInt(txtEstimasi.getText().trim());
            } catch (NumberFormatException ex) {
                estimasi = 0;
            }
            if (estimasi < 1) {
                tandaiError(txtEstimasi, lblErrorEstimasi, "Harus angka bulat, minimal 1");
                valid = false;
            }
        }
        return valid ? new Layanan(nama, harga, estimasi) : null;
    }

