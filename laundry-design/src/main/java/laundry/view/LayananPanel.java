    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        Layanan baru = bacaForm();
        if (baru == null) {
            return;
        }
        try {
            layananDAO.insert(baru);
            loadData();
            resetForm();
            tampilkanSukses(lblSukses, "Data tersimpan");
        } catch (SQLException ex) {
            showErrorDatabase("menyimpan layanan", ex);
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        if (idTerpilih < 0) {
            showPeringatan("Klik dulu data layanan di tabel yang ingin diubah.");
            return;
        }
        Layanan l = bacaForm();
        if (l == null) {
            return;
        }
        try {
            // harga baru hanya berlaku untuk transaksi berikutnya (transaksi lama menyimpan salinan harga)
            l.setIdLayanan(idTerpilih);
            layananDAO.update(l);
            loadData();
            resetForm();
            tampilkanSukses(lblSukses, "Perubahan tersimpan");
        } catch (SQLException ex) {
            showErrorDatabase("mengubah layanan", ex);
        }
    }//GEN-LAST:event_btnUbahActionPerformed

