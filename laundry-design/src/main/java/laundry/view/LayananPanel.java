    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        if (idTerpilih < 0) {
            showPeringatan("Klik dulu data layanan di tabel yang ingin dihapus.");
            return;
        }
        if (!konfirmasi("Hapus layanan \"" + txtNamaLayanan.getText() + "\"?")) {
            return;
        }
        try {
            // layanan yang sudah dipakai transaksi hanya dinonaktifkan (lihat LayananDAO.delete)
            boolean dipakai = transaksiDAO.adaLayanan(idTerpilih);
            layananDAO.delete(idTerpilih);
            loadData();
            resetForm();
            if (dipakai) {
                showInfo("Layanan sudah dipakai di transaksi, jadi hanya dinonaktifkan.\nRiwayat transaksinya tetap tersimpan.");
            } else {
                tampilkanSukses(lblSukses, "Data dihapus");
            }
        } catch (SQLException ex) {
            showErrorDatabase("menghapus layanan", ex);
        }
    }//GEN-LAST:event_btnHapusActionPerformed

    private void tblLayananMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblLayananMouseClicked
        // klik baris tabel: tampilkan datanya di form untuk diubah/dihapus
        int baris = tblLayanan.getSelectedRow();
        if (baris < 0) {
            return;
        }
        try {
            Layanan l = layananDAO.findById((int) tblLayanan.getValueAt(baris, 0));
            idTerpilih = l.getIdLayanan();
            txtNamaLayanan.setText(l.getNamaLayanan());
            txtHarga.setText(String.valueOf(Math.round(l.getHargaPerKg())));
            txtEstimasi.setText(String.valueOf(l.getEstimasiHari()));
            hapusError(txtNamaLayanan, lblErrorNama);
            hapusError(txtHarga, lblErrorHarga);
            hapusError(txtEstimasi, lblErrorEstimasi);
        } catch (SQLException ex) {
            showErrorDatabase("memuat layanan", ex);
        }
    }//GEN-LAST:event_tblLayananMouseClicked

